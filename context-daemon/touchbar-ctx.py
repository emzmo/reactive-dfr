#!/usr/bin/env python3
"""touchbar-ctx — Touch Bar context manager CLI.

Manage contextual layouts for the Touch Bar (tiny-dfr + context-daemon).

Subcommands:
  list              List all available contexts
  show <name>       Display a context's layout
  new <name>        Scaffold a new context template + add matcher entry
  test <name>       Apply a context immediately (writes config.toml)
  validate [file]   Validate a TOML config file (syntax, keys, icons)
  matcher           Show or edit matcher rules
  backends          List available compositor backends

Usage:
  touchbar-ctx list
  touchbar-ctx new ide --class "code" --class "vscodium"
  touchbar-ctx test browser
  touchbar-ctx validate
"""

import argparse
import os
import shutil
import subprocess
import sys
import tomllib
from pathlib import Path

CONFIG_DIR = Path(os.environ.get("TOUCHBAR_CONFIG_DIR", "/etc/touchbar-daemon/config"))
CONTEXTS_DIR = CONFIG_DIR / "contexts"
MATCHER_PATH = CONFIG_DIR / "matcher.toml"
BASE_PATH = CONFIG_DIR / "base.toml"
OUT_PATH = Path(os.environ.get("TOUCHBAR_OUT", "/etc/tiny-dfr/config.toml"))

# Add the daemon lib dir to import path for composer/matcher
LIB_DIR = Path(os.environ.get("TOUCHBAR_LIB_DIR", "/usr/local/lib/touchbar-daemon"))
if LIB_DIR.exists():
    sys.path.insert(0, str(LIB_DIR))


def load_contexts():
    """Return dict of context_name -> path."""
    if not CONTEXTS_DIR.exists():
        return {}
    return {
        f.stem: f
        for f in CONTEXTS_DIR.glob("*.toml")
    }


def load_matcher():
    """Load matcher.toml as a list of rules."""
    if not MATCHER_PATH.exists():
        return []
    with open(MATCHER_PATH, "rb") as f:
        data = tomllib.load(f)
    return data.get("context", [])


def cmd_list(args):
    """List all available contexts."""
    contexts = load_contexts()
    matcher = load_matcher()
    matched_names = {r.get("name") for r in matcher}

    if not contexts:
        print("No contexts found in", CONTEXTS_DIR)
        return 1

    print(f"{'Name':<16} {'Matched':<8} {'Description'}")
    print("-" * 60)
    for name in sorted(contexts):
        matched = "yes" if name in matched_names else "no"
        desc = ""
        try:
            with open(contexts[name], "rb") as f:
                data = tomllib.load(f)
            buttons = data.get("PrimaryLayerKeys", [])
            desc = f"{len(buttons)} buttons"
        except Exception:
            desc = "(parse error)"
        print(f"{name:<16} {matched:<8} {desc}")
    print(f"\n{len(contexts)} contexts, {len(matched_names)} matched")
    return 0


def cmd_show(args):
    """Show a context's layout."""
    ctx_path = CONTEXTS_DIR / f"{args.name}.toml"
    if not ctx_path.exists():
        print(f"Context '{args.name}' not found at {ctx_path}", file=sys.stderr)
        return 1
    print(ctx_path.read_text())
    return 0


