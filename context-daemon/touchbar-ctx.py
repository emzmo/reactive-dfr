def cmd_validate(args):
    """Validate TOML config files."""
    errors = 0
    warnings = 0

    files_to_check = []
    if args.file:
        files_to_check = [Path(args.file)]
    else:
        # Validate all context files + base + matcher
        if BASE_PATH.exists():
            files_to_check.append(BASE_PATH)
        if MATCHER_PATH.exists():
            files_to_check.append(MATCHER_PATH)
        files_to_check.extend(load_contexts().values())

    for fpath in files_to_check:
        name = fpath.name
        # 1. Parse TOML
        try:
            with open(fpath, "rb") as f:
                data = tomllib.load(f)
        except Exception as e:
            print(f"  ERROR: {name}: TOML parse error: {e}")
            errors += 1
            continue

        # 2. Check button configs
        for layer_key in ("PrimaryLayerKeys", "MediaLayerKeys"):
            if layer_key not in data:
                continue
            buttons = data[layer_key]
            if not isinstance(buttons, list):
                print(f"  ERROR: {name}: {layer_key} must be a list")
                errors += 1
                continue
            if layer_key == "PrimaryLayerKeys" and not buttons:
                print(f"  WARNING: {name}: PrimaryLayerKeys is empty")
                warnings += 1
            for i, btn in enumerate(buttons):
                if not isinstance(btn, dict):
                    print(f"  ERROR: {name}: {layer_key}[{i}] is not a table")
                    errors += 1
                    continue
                # Check action keys
                action = btn.get("Action")
                if action is not None:
                    keys = action if isinstance(action, list) else [action]
                    for k in keys:
                        if k not in VALID_KEYS:
                            print(f"  WARNING: {name}: {layer_key}[{i}] action '{k}' may not be a valid Key")
                            warnings += 1
                # Check icon paths
                icon = btn.get("Icon")
                if icon:
                    for search in (f"/etc/tiny-dfr/{icon}.svg", f"/etc/tiny-dfr/{icon}.png",
                                   f"/usr/share/tiny-dfr/{icon}.svg", f"/usr/share/tiny-dfr/{icon}.png"):
                        if Path(search).exists():
                            break
                    else:
                        if not btn.get("Theme"):
                            print(f"  WARNING: {name}: {layer_key}[{i}] icon '{icon}' not found")
                            warnings += 1
                # Check mutually exclusive fields
                exclusive = [k for k in ("Text", "Icon", "Time", "Battery") if btn.get(k) is not None]
                if len(exclusive) > 1:
                    print(f"  WARNING: {name}: {layer_key}[{i}] has multiple of Text/Icon/Time/Battery (behavior undefined)")
                    warnings += 1

        # 3. Check global config keys
        for key in data:
            if key in ("PrimaryLayerKeys", "MediaLayerKeys", "context"):
                continue
            known_globals = ("MediaLayerDefault", "ShowButtonOutlines", "EnablePixelShift",
                             "FontTemplate", "AdaptiveBrightness", "ActiveBrightness",
                             "DoublePressSwitchLayers")
            if key not in known_globals and key not in ("Text", "Icon", "Theme", "Time",
                    "Battery", "Locale", "Action", "Stretch", "IconWidth", "IconHeight",
                    "Submenu", "Slide", "Widget", "LongPress", "ColorPickerCommand"):
                print(f"  WARNING: {name}: unknown key '{key}'")
                warnings += 1

        # 4. Check matcher for unreachable contexts
        if name == "matcher.toml":
            contexts = load_contexts()
            for rule in data.get("context", []):
                cname = rule.get("name", "")
                if cname and cname not in contexts:
                    print(f"  WARNING: matcher references context '{cname}' which has no file")
                    warnings += 1

        status = "OK" if errors == 0 and warnings == 0 else f"{errors} error(s), {warnings} warning(s)"
        print(f"  {name}: {status}")

    print(f"\nValidation complete: {errors} error(s), {warnings} warning(s)")
    return 1 if errors > 0 else 0


def cmd_matcher(args):
    """Show or edit matcher rules."""
    if not MATCHER_PATH.exists():
        print(f"Matcher not found: {MATCHER_PATH}")
        return 1

    rules = load_matcher()
    if not rules:
        print("No matcher rules defined.")
        return 0

    print(f"{'#':<3} {'Name':<16} {'Classes':<40} {'Titles'}")
    print("-" * 80)
    for i, rule in enumerate(rules):
        name = rule.get("name", "?")
        classes = ", ".join(rule.get("class", []))
        titles = ", ".join(rule.get("title", []))
        print(f"{i:<3} {name:<16} {classes:<40} {titles}")
    return 0


def cmd_backends(args):
    """List available compositor backends."""
    backends = [
        ("hyprland", "Hyprland", "via .socket2.sock + hyprctl -j activewindow"),
        ("sway", "Sway/i3", "via swaymsg -t get_tree (focused window)"),
    ]
    print(f"{'Backend':<12} {'Compositor':<12} {'Method'}")
    print("-" * 70)
    for key, name, method in backends:
        # Check if available
        available = ""
        if key == "hyprland":
            sig = os.environ.get("HYPRLAND_INSTANCE_SIGNATURE")
            available = " (active)" if sig else ""
        elif key == "sway":
            sock = os.environ.get("SWAYSOCK")
            available = " (active)" if sock else ""
        print(f"{key:<12} {name:<12} {method}{available}")
    return 0


def main():
    parser = argparse.ArgumentParser(
        prog="touchbar-ctx",
        description="Touch Bar context manager — create, test, and validate contexts"
    )
    sub = parser.add_subparsers(dest="command", required=True)

    p_list = sub.add_parser("list", help="List all contexts")
    p_list.set_defaults(func=cmd_list)

    p_show = sub.add_parser("show", help="Show a context's layout")
    p_show.add_argument("name", help="Context name")
    p_show.set_defaults(func=cmd_show)

    p_new = sub.add_parser("new", help="Scaffold a new context")
    p_new.add_argument("name", help="Context name (filename)")
    p_new.add_argument("--class", dest="class_names", action="append", help="Window class(es) to match")
    p_new.add_argument("--title", action="append", help="Window title substring(s) to match")
    p_new.add_argument("--description", help="Context description")
    p_new.add_argument("--force", action="store_true", help="Overwrite existing")
    p_new.set_defaults(func=cmd_new)

    p_test = sub.add_parser("test", help="Apply a context immediately")
    p_test.add_argument("name", help="Context name")
    p_test.add_argument("--dry-run", action="store_true", help="Print config without writing")
    p_test.set_defaults(func=cmd_test)

    p_validate = sub.add_parser("validate", help="Validate config files")
    p_validate.add_argument("file", nargs="?", help="Specific file to validate (default: all)")
    p_validate.set_defaults(func=cmd_validate)

    p_matcher = sub.add_parser("matcher", help="Show matcher rules")
    p_matcher.set_defaults(func=cmd_matcher)

    p_backends = sub.add_parser("backends", help="List compositor backends")
    p_backends.set_defaults(func=cmd_backends)

    args = parser.parse_args()
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())