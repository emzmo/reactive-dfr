def cmd_new(args):
    """Scaffold a new context + add to matcher.toml."""
    ctx_path = CONTEXTS_DIR / f"{args.name}.toml"
    if ctx_path.exists():
        print(f"Context '{args.name}' already exists at {ctx_path}", file=sys.stderr)
        if not args.force:
            return 1
        print("Overwriting (--force)")

    CONTEXTS_DIR.mkdir(parents=True, exist_ok=True)

    description = args.description or f"Custom context: {args.name}"
    content = CONTEXT_TEMPLATE.replace("{NAME}", args.name).replace("{DESCRIPTION}", description)
    ctx_path.write_text(content)
    print(f"Created: {ctx_path}")

    # Add matcher entry if classes/titles provided
    classes = args.class_names or []
    titles = args.title or []
    if classes or titles:
        _add_matcher_entry(args.name, classes, titles)
        print(f"Added matcher entry for '{args.name}'")
    else:
        print("No --class/--title provided — add manually to matcher.toml")

    print(f"\nEdit {ctx_path} to customize, then run: touchbar-ctx test {args.name}")
    return 0


def _add_matcher_entry(name, classes, titles):
    """Append a [[context]] block to matcher.toml."""
    lines = []
    lines.append("")
    lines.append(f"[[context]]")
    lines.append(f'name = "{name}"')
    if classes:
        class_str = ", ".join(f'"{c}"' for c in classes)
        lines.append(f"class = [ {class_str} ]")
    if titles:
        title_str = ", ".join(f'"{t}"' for t in titles)
        lines.append(f"title = [ {title_str} ]")
    lines.append("")

    with open(MATCHER_PATH, "a") as f:
        f.write("\n".join(lines) + "\n")


def cmd_test(args):
    """Apply a context immediately by composing config.toml."""
    ctx_path = CONTEXTS_DIR / f"{args.name}.toml"
    if not ctx_path.exists():
        print(f"Context '{args.name}' not found at {ctx_path}", file=sys.stderr)
        return 1

    try:
        from composer import compose, write_atomic
    except ImportError:
        # Fallback: inline compose
        text = _compose_inline(ctx_path)
        write_inline = True
    else:
        text = compose(BASE_PATH, ctx_path)
        write_inline = False

    if args.dry_run:
        print(text)
        return 0

    if write_inline:
        _write_atomic_inline(text, OUT_PATH)
    else:
        write_atomic(text, OUT_PATH)

    print(f"Applied context '{args.name}' -> {OUT_PATH}")
    print("(tiny-dfr hot-reloads via inotify)")
    return 0


def _compose_inline(ctx_path):
    """Minimal compose without the daemon lib."""
    import tempfile
    base = {}
    if BASE_PATH.exists():
        with open(BASE_PATH, "rb") as f:
            base = tomllib.load(f)
    with open(ctx_path, "rb") as f:
        ctx = tomllib.load(f)

    lines = []
    for key in ("MediaLayerDefault", "ShowButtonOutlines", "EnablePixelShift",
                "FontTemplate", "AdaptiveBrightness", "ActiveBrightness",
                "DoublePressSwitchLayers"):
        if key in base:
            v = base[key]
            if isinstance(v, bool):
                lines.append(f"{key} = {'true' if v else 'false'}")
            elif isinstance(v, str):
                lines.append(f'{key} = "{v}"')
            else:
                lines.append(f"{key} = {v}")

    # PrimaryLayerKeys
    buttons = ctx.get("PrimaryLayerKeys", [])
    if buttons:
        body = ",\n    ".join(_fmt_button(b) for b in buttons)
        lines.append(f"PrimaryLayerKeys = [\n    {body}\n]")
    else:
        lines.append("PrimaryLayerKeys = []")

    # MediaLayerKeys
    if "MediaLayerKeys" in base:
        body = ",\n    ".join(_fmt_button(b) for b in base["MediaLayerKeys"])
        lines.append(f"MediaLayerKeys = [\n    {body}\n]")

    return "\n".join(lines) + "\n"


def _fmt_button(b):
    parts = []
    for key in ("Text", "Icon", "Theme", "Time", "Battery", "Locale"):
        if key in b:
            parts.append(f'{key} = "{b[key]}"')
    if "Action" in b:
        action = b["Action"]
        if isinstance(action, list):
            parts.append("Action = [" + ", ".join(f'"{a}"' for a in action) + "]")
        else:
            parts.append(f'Action = "{action}"')
    for key in ("Stretch", "IconWidth", "IconHeight"):
        if key in b:
            parts.append(f"{key} = {b[key]}")
    return "{ " + ", ".join(parts) + " }"


def _write_atomic_inline(text, out_path):
    import tempfile
    out_path = Path(out_path)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=out_path.parent, prefix=".config.toml.")
    try:
        with os.fdopen(fd, "w") as f:
            f.write(text)
        os.chmod(tmp, 0o644)
        os.replace(tmp, out_path)
    finally:
        if os.path.exists(tmp):
            os.unlink(tmp)


